/** Normalize a Strapi `platform` enum value (lowercase) to a known icon key. */
export function platformKey(input: string | undefined | null): SocialPlatform | null {
	if (!input) return null;
	const k = input.trim().toLowerCase();
	if (k in SOCIAL_ICONS) return k as SocialPlatform;
	// Common aliases
	if (k === 'fb') return 'facebook';
	if (k === 'ig') return 'instagram';
	if (k === 'tw' || k === 'x.com') return 'x';
	if (k === 'wa') return 'whatsapp';
	if (k === 'mail') return 'email';
	return null;
}
